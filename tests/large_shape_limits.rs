fn rel(got: f64, want: f64, other: f64) -> f64 {
    // relative to the smaller of the two tails
    (got - want).abs() / want.min(other).max(1e-300)
}

/// Past a shape of 1e7 the continued fraction still holds `~1e-10` of the smaller
/// tail (it was the normal limit, off by 1e-5 of the tail at 1e7, until 3e11);
/// from 3e11 the limit takes over, `1.2e-9` of the far tail at the worst row (a
/// skewed `1e12 : 3e13` pair) and `~1e-12` at the centre of 1e14.
#[test]
fn the_beta_holds_its_digits_to_a_shape_of_1e14() {
    for &(x, a, b, want) in &BETA {
        let got = regularized_incomplete_beta(x, a, b);
        let e = rel(got, want, 1.0 - want);
        assert!(
            e <= 1.5e-9,
            "I_{x:e}({a:e}, {b:e}) = {got:e}, want {want:e}: {e:.2e}"
        );
    }
}

/// Series and continued fraction hold `~1.5e-10` to 1e10; from there the
/// Wilson–Hilferty limit (`8e-10` of the smaller tail at 1e10).
#[test]
fn the_gamma_holds_its_digits_to_a_shape_of_1e10() {
    for &(x, a, p, q) in &GAMMA {
        let (got, e) = if p <= q {
            let g = regularized_lower_gamma(a, x);
            (g, rel(g, p, q))
        } else {
            let g = regularized_upper_gamma(a, x);
            (g, rel(g, q, p))
        };
        assert!(e <= 1e-9, "P/Q({a:e}, {x:e}) = {got:e}: {e:.2e}");
    }
}
