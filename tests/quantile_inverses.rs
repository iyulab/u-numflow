//! The t, F and chi-squared quantiles and the incomplete gamma and beta inverses
//! beneath them, against 50-digit references (mpmath 1.4.1 at 60 digits, the root
//! of the incomplete function itself — never of a float approximation), over the
//! probabilities a test uses (0.9, 0.975, 0.999), the ones a p-value falls to
//! (1e-5 … 1e-300) and the upper tails written as `1 - 1e-14`.
//!
//! The previous implementations are kept below as `old` so the cases where they
//! were already right are compared as well: the new code must not be worse there.
#![allow(clippy::excessive_precision, clippy::approx_constant)]

use u_numflow::special::{
    chi_squared_quantile, f_distribution_quantile, inverse_regularized_incomplete_beta,
    inverse_regularized_lower_gamma, inverse_regularized_upper_gamma, regularized_incomplete_beta,
    regularized_lower_gamma, regularized_upper_gamma, t_distribution_quantile,
};

/// The implementations this change replaced: Newton on the CDF from the normal
/// quantile (t), and bisection on the CDF (F, chi-squared).
mod old {
    use u_numflow::special::{
        chi_squared_cdf, f_distribution_cdf, inverse_normal_cdf, t_distribution_cdf,
        t_distribution_pdf,
    };

    pub fn t(p: f64, df: f64) -> f64 {
        if (p - 0.5).abs() < 1e-15 {
            return 0.0;
        }
        let mut t = inverse_normal_cdf(p);
        for _ in 0..50 {
            let cdf = t_distribution_cdf(t, df);
            let pdf = t_distribution_pdf(t, df);
            if pdf.abs() < 1e-300 {
                break;
            }
            let delta = (cdf - p) / pdf;
            t -= delta;
            if delta.abs() < 1e-12 * t.abs().max(1.0) {
                break;
            }
        }
        t
    }

    pub fn f(p: f64, df1: f64, df2: f64) -> f64 {
        let mut hi = 2.0;
        while f_distribution_cdf(hi, df1, df2) < p {
            hi *= 2.0;
            if hi > 1e15 {
                return hi;
            }
        }
        let mut lo = 0.0f64;
        for _ in 0..200 {
            let mid = (lo + hi) / 2.0;
            if hi - lo < 1e-12 * mid.max(1e-15) {
                break;
            }
            if f_distribution_cdf(mid, df1, df2) < p {
                lo = mid;
            } else {
                hi = mid;
            }
        }
        (lo + hi) / 2.0
    }

    pub fn chi(p: f64, k: f64) -> f64 {
        let mut hi = k.max(1.0);
        while chi_squared_cdf(hi, k) < p {
            hi *= 2.0;
            if hi > 1e15 {
                return hi;
            }
        }
        let mut lo = 0.0f64;
        for _ in 0..200 {
            let mid = (lo + hi) / 2.0;
            if hi - lo < 1e-13 * mid.max(1e-300) {
                break;
            }
            if chi_squared_cdf(mid, k) < p {
                lo = mid;
            } else {
                hi = mid;
            }
        }
        (lo + hi) / 2.0
    }
}

fn rel(got: f64, want: f64) -> f64 {
    ((got - want) / want).abs()
}

