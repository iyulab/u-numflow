// The error bound of a quantile is the incomplete function's own: past a shape of
// about 1e3 the continued fraction's argument `1 - x` is a rounded double whose
// absolute error 1e-16 is a relative error of `1e-16 * shape` in a root of order
// `1 / shape`. The bound below follows that line instead of hiding it.
fn shape_tolerance(shape: f64) -> f64 {
    1e-13 + 3e-17 * shape
}

fn ordinary(p: f64) -> bool {
    (1e-5..=1.0 - 1e-5).contains(&p)
}

#[test]
fn t_quantile_matches_the_reference_at_every_probability() {
    for &(p, df, want) in &T_CASES {
        let got = t_distribution_quantile(p, df);
        assert!(
            rel(got, want) <= shape_tolerance(df),
            "t(p={p:e}, df={df}) = {got:e}, want {want:e}"
        );
    }
}

#[test]
fn f_quantile_matches_the_reference_at_every_probability() {
    for &(p, d1, d2, want) in &F_CASES {
        let got = f_distribution_quantile(p, d1, d2);
        assert!(
            rel(got, want) <= shape_tolerance(d1.max(d2)),
            "F(p={p:e}, {d1}, {d2}) = {got:e}, want {want:e}"
        );
    }
}

#[test]
fn chi_squared_quantile_matches_the_reference_at_every_probability() {
    for &(p, k, want) in &CHI_CASES {
        let got = chi_squared_quantile(p, k);
        assert!(
            rel(got, want) <= shape_tolerance(k / 100.0),
            "chi2(p={p:e}, k={k}) = {got:e}, want {want:e}"
        );
    }
}

/// Where the previous implementations were right (a probability a test uses, a
/// shape of ordinary size) the new ones are not worse.
#[test]
fn ordinary_probabilities_are_no_worse_than_before() {
    let slack = |old: f64, shape: f64| 2.0 * old + shape_tolerance(shape);
    let mut compared = 0;
    for &(p, df, want) in T_CASES.iter().filter(|c| ordinary(c.0)) {
        let (new, old) = (
            rel(t_distribution_quantile(p, df), want),
            rel(old::t(p, df), want),
        );
        assert!(
            new <= slack(old, df),
            "t(p={p}, df={df}): {new:e} vs old {old:e}"
        );
        compared += 1;
    }
    for &(p, d1, d2, want) in F_CASES.iter().filter(|c| ordinary(c.0)) {
        let (new, old) = (
            rel(f_distribution_quantile(p, d1, d2), want),
            rel(old::f(p, d1, d2), want),
        );
        assert!(
            new <= slack(old, d1.max(d2)),
            "F(p={p}, {d1}, {d2}): {new:e} vs old {old:e}"
        );
        compared += 1;
    }
    for &(p, k, want) in CHI_CASES.iter().filter(|c| ordinary(c.0)) {
        let (new, old) = (
            rel(chi_squared_quantile(p, k), want),
            rel(old::chi(p, k), want),
        );
        assert!(
            new <= slack(old, k / 100.0),
            "chi2(p={p}, k={k}): {new:e} vs old {old:e}"
        );
        compared += 1;
    }
    assert!(compared > 150, "{compared}");
}

/// The cases the previous implementations got wrong, as the reference.
#[test]
fn the_cases_that_were_wrong_are_right() {
    // Cauchy: t(1) at p = 1e-30 is −1/(π p) = −3.183e29 (was off by a factor of 2).
    let t = t_distribution_quantile(1e-30, 1.0);
    assert!(rel(t, -3.183098861837907e29) < 1e-13, "{t:e}");
    // F(2, 5) at p = 1e-10: 4e-11 (was 400 times too large).
    let want = F_CASES
        .iter()
        .find(|c| c.0 == 1e-10 && c.1 == 2.0 && c.2 == 5.0)
        .unwrap()
        .3;
    assert!(rel(f_distribution_quantile(1e-10, 2.0, 5.0), want) < 1e-13);
    // chi-squared(1) at p = 1e-10 (was 1 % off).
    let want = CHI_CASES
        .iter()
        .find(|c| c.0 == 1e-10 && c.1 == 1.0)
        .unwrap()
        .2;
    assert!(rel(chi_squared_quantile(1e-10, 1.0), want) < 1e-13);
}

