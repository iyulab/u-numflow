#[test]
fn beta_inverse_matches_the_reference() {
    for &(p, a, b, x, y) in &BETA_CASES {
        let got = inverse_regularized_incomplete_beta(p, a, b);
        if x <= 0.5 {
            assert!(
                rel(got, x) <= shape_tolerance(a.max(b)),
                "I^-1(p={p:e}, {a}, {b}) = {got:e}, want {x:e}"
            );
        } else {
            // a root near 1 is a double near 1: its resolution is 1 − x to 1e-16
            assert!(
                (got - x).abs() <= 4e-16,
                "I^-1(p={p:e}, {a}, {b}) = {got}, want {x} (1 - x = {y:e})"
            );
        }
    }
}

/// The two tails are one function: the lower inverse at `p` and the upper inverse
/// at `1 - p` name the same `x`, and the beta inverse mirrors.
#[test]
fn the_tails_agree() {
    for &(a, p) in &[(0.5, 0.3), (2.5, 0.75), (30.0, 0.5), (1.0, 0.125)] {
        let lower = inverse_regularized_lower_gamma(a, p);
        let upper = inverse_regularized_upper_gamma(a, 1.0 - p);
        assert!(rel(lower, upper) < 1e-13, "{a} {p}: {lower} {upper}");
        assert!((regularized_lower_gamma(a, lower) - p).abs() < 1e-13);
        assert!((regularized_upper_gamma(a, lower) - (1.0 - p)).abs() < 1e-13);
    }
    for &(a, b, p) in &[(2.0, 3.0, 0.3), (0.5, 0.5, 0.75), (7.0, 1.5, 0.125)] {
        let x = inverse_regularized_incomplete_beta(p, a, b);
        let mirrored = inverse_regularized_incomplete_beta(1.0 - p, b, a);
        assert!(
            (x - (1.0 - mirrored)).abs() < 4e-16,
            "{a} {b} {p}: {x} {mirrored}"
        );
        assert!((regularized_incomplete_beta(x, a, b) - p).abs() < 1e-13);
    }
}

#[test]
fn t_quantile_is_odd_and_monotone() {
    for &df in &[0.5, 1.0, 7.0, 1e4] {
        // 1 − p is exact for these, so the two sides are mirror images to the bit
        for &p in &[0.25, 0.0625, 0.125] {
            let lo = t_distribution_quantile(p, df);
            let hi = t_distribution_quantile(1.0 - p, df);
            assert!(lo < 0.0 && hi > 0.0);
            assert!(rel(lo, -hi) < 1e-15, "df={df} p={p}: {lo} {hi}");
        }
        assert_eq!(t_distribution_quantile(0.5, df), 0.0);
        let mut last = f64::NEG_INFINITY;
        for k in 1..400 {
            let p = k as f64 / 400.0;
            let t = t_distribution_quantile(p, df);
            assert!(t > last, "df={df}: t({p}) = {t} after {last}");
            last = t;
        }
    }
}

/// A quantile past what a double holds is an infinity, never a number from a
/// bracket (the previous bisections returned their 1e15 limit as the answer).
#[test]
fn out_of_range_quantiles_are_infinite() {
    assert_eq!(t_distribution_quantile(1e-300, 0.25), f64::NEG_INFINITY);
    assert_eq!(t_distribution_quantile(1.0 - 1e-16, 0.01), f64::INFINITY);
    assert_eq!(
        f_distribution_quantile(1.0 - 1e-16, 1.0, 0.1),
        f64::INFINITY
    );
    assert!(chi_squared_quantile(1.0 - 1e-16, 1e-3).is_finite());
}

#[test]
fn degenerate_arguments() {
    for bad in [f64::NAN, 0.0, 1.0, -0.5, 2.0] {
        assert!(t_distribution_quantile(bad, 5.0).is_nan());
        assert!(f_distribution_quantile(bad, 5.0, 3.0).is_nan());
        assert!(chi_squared_quantile(bad, 5.0).is_nan());
    }
    for bad in [f64::NAN, 0.0, -1.0] {
        assert!(t_distribution_quantile(0.3, bad).is_nan());
        assert!(f_distribution_quantile(0.3, bad, 2.0).is_nan());
        assert!(f_distribution_quantile(0.3, 2.0, bad).is_nan());
        assert!(chi_squared_quantile(0.3, bad).is_nan());
        assert!(inverse_regularized_lower_gamma(bad, 0.3).is_nan());
        assert!(inverse_regularized_upper_gamma(bad, 0.3).is_nan());
        assert!(inverse_regularized_incomplete_beta(0.3, bad, 2.0).is_nan());
        assert!(inverse_regularized_incomplete_beta(0.3, 2.0, bad).is_nan());
    }
    assert!(inverse_regularized_lower_gamma(2.0, 1.5).is_nan());
    assert!(inverse_regularized_upper_gamma(2.0, -0.1).is_nan());
    assert!(inverse_regularized_incomplete_beta(f64::NAN, 2.0, 3.0).is_nan());
    assert_eq!(inverse_regularized_lower_gamma(2.0, 0.0), 0.0);
    assert_eq!(inverse_regularized_lower_gamma(2.0, 1.0), f64::INFINITY);
    assert_eq!(inverse_regularized_upper_gamma(2.0, 1.0), 0.0);
    assert_eq!(inverse_regularized_upper_gamma(2.0, 0.0), f64::INFINITY);
    assert_eq!(inverse_regularized_incomplete_beta(0.0, 2.0, 3.0), 0.0);
    assert_eq!(inverse_regularized_incomplete_beta(1.0, 2.0, 3.0), 1.0);
}
