fn rel(got: f64, want: f64, other: f64) -> f64 {
    (got - want).abs() / want.min(other).max(1e-300)
}

/// The two-sided p-value `2 sf(t)` and the CDF of a t statistic keep their digits at
/// any degrees of freedom: `1 - x` of `x = df / (df + t^2)` used to be rounded before
/// the incomplete beta, and a large `df` multiplied that by `df` (5e-7 at 1e10).
#[test]
fn the_t_distribution_holds_its_digits_at_any_degrees_of_freedom() {
    for &(t, df, two) in &T {
        let p = 2.0 * t_distribution_sf(t, df);
        let e = rel(p, two, 1.0 - two);
        assert!(
            e <= 1e-12,
            "2 sf({t}, {df:e}) = {p:e}, want {two:e}: {e:.2e}"
        );
        let cdf = t_distribution_cdf(-t, df) * 2.0;
        let e = rel(cdf, two, 1.0 - two);
        assert!(
            e <= 1e-12,
            "2 cdf(-{t}, {df:e}) = {cdf:e}, want {two:e}: {e:.2e}"
        );
    }
}

/// The quantile and the CDF agree to the conditioning of the problem: a double `t`
/// is good to 1e-16 relative, which a probability resolves to `t^2 * 1e-16`.
#[test]
fn the_t_quantile_round_trips_at_large_degrees_of_freedom() {
    for df in [1e5, 1e7, 1e9, 1e10, 1e12, 1e14] {
        for p in [1e-12, 1e-6, 0.01, 0.3, 0.975, 1.0 - 1e-6] {
            let t = t_distribution_quantile(p, df);
            let back = t_distribution_cdf(t, df);
            let e = (back - p).abs() / p.min(1.0 - p);
            assert!(
                e <= 1e-11,
                "cdf(quantile({p:e}, {df:e})) = {back:e}: {e:.2e}"
            );
        }
    }
}

/// The F CDF and survival function from the pair `d1 x / (d1 x + d2)`, `d2 / (d1 x + d2)`.
#[test]
fn the_f_distribution_holds_its_digits_at_large_degrees_of_freedom() {
    for &(x, d1, d2, want, upper) in &F {
        let cdf = f_distribution_cdf(x, d1, d2);
        let e = rel(cdf, want, upper);
        assert!(
            e <= MAXF,
            "F cdf({x}, {d1:e}, {d2:e}) = {cdf:e}, want {want:e}: {e:.2e}"
        );
        let sf = f_distribution_sf(x, d1, d2);
        let e = rel(sf, upper, want);
        assert!(
            e <= MAXF,
            "F sf({x}, {d1:e}, {d2:e}) = {sf:e}, want {:e}: {e:.2e}",
            upper
        );
    }
}

/// Measured worst: 3.7e-11 (a pair near 1e10), up to 1e-9 where the normal limit takes over.
const MAXF: f64 = 1e-9;
