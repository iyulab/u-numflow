fn eval(name: &str, a: &[f64]) -> f64 {
    match name {
        "ln_gamma" => s::ln_gamma(a[0]),
        "gamma" => s::gamma(a[0]),
        "ln_beta" => s::ln_beta(a[0], a[1]),
        "erf" => s::erf(a[0]),
        "erfc" => s::erfc(a[0]),
        "weibull_variance" => Weibull::new(a[0], 1.0).expect("valid").variance(),
        "weibull_mean" => Weibull::new(a[0], 1.0).expect("valid").mean(),
        "weibull_variance_scaled" => Weibull::new(a[0], a[1]).expect("valid").variance(),
        other => panic!("unknown function {other}"),
    }
}

#[test]
fn every_row_matches_its_reference_to_a_few_ulps() {
    let mut worst = 0.0_f64;
    for &(name, args, want) in ROWS {
        let got = eval(name, args);
        let rel = ((got - want) / want).abs();
        worst = worst.max(rel);
        assert!(
            rel <= 3e-15,
            "{name}{args:?} = {got:e}, reference {want:e} (relative error {rel:e})"
        );
    }
    eprintln!("worst relative error over {} rows: {worst:e}", ROWS.len());
}

/// Γ(x) for a negative x: signed, the poles are NaN.
#[test]
fn the_gamma_function_of_a_negative_argument_is_signed_and_the_poles_are_nan() {
    let sqrt_pi = std::f64::consts::PI.sqrt();
    for (x, want) in [
        (-0.5, -2.0 * sqrt_pi),
        (-1.5, 4.0 * sqrt_pi / 3.0),
        (-2.5, -8.0 * sqrt_pi / 15.0),
        (-3.5, 16.0 * sqrt_pi / 105.0),
    ] {
        assert!(
            (s::gamma(x) / want - 1.0).abs() < 3e-15,
            "Γ({x}) = {}",
            s::gamma(x)
        );
        // ln |Γ| is the log of the magnitude whatever the sign.
        assert!(
            (s::ln_gamma(x) - want.abs().ln()).abs() < 3e-15,
            "ln|Γ({x})|"
        );
    }
    for x in [-1.0, -2.0, -3.0, -1e10] {
        assert!(s::gamma(x).is_nan(), "Γ({x}) is a pole");
        assert_eq!(s::ln_gamma(x), f64::INFINITY, "ln|Γ({x})| at a pole");
    }
    assert_eq!(s::gamma(0.0), f64::INFINITY);
    assert_eq!(s::gamma(-0.0), f64::NEG_INFINITY);
    assert_eq!(s::gamma(172.0), f64::INFINITY);
    assert!(s::gamma(f64::NAN).is_nan() && s::ln_gamma(f64::NAN).is_nan());
}

/// Γ(x + 1) = x Γ(x) across the ranges the evaluation switches at.
#[test]
fn the_recurrence_holds_across_the_ranges_the_evaluation_switches_at() {
    for x in [
        0.3, 0.5, 1.2, 1.5, 2.3, 2.5, 4.7, 9.0, 9.99, 10.0, 15.5, 60.0, 120.5, 170.0,
    ] {
        let (lhs, rhs) = (s::gamma(x + 1.0), x * s::gamma(x));
        assert!(
            (lhs / rhs - 1.0).abs() < 1e-14,
            "x = {x}: {lhs:e} vs {rhs:e}"
        );
    }
}
