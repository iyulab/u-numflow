/// The largest absolute error of `eval` over `rows` (the p-values these feed
/// are compared with a significance level, so the absolute error is the one
/// that decides), and where it is.
fn worst_absolute<T>(rows: &[T], eval: impl Fn(&T) -> (f64, f64, String)) -> (f64, String) {
    let mut worst = (0.0_f64, String::new());
    for row in rows {
        let (got, want, label) = eval(row);
        let err = (got - want).abs();
        if err > worst.0 {
            worst = (err, format!("{label}: {got:e} vs {want:e}"));
        }
    }
    worst
}

/// `P(a, x)` at shapes from 1e4 to 1e12, within 1e-9 -- what the changelog
/// promises -- of the integral of the density at 60 digits.
#[test]
fn the_regularized_lower_gamma_is_right_to_1e_9_at_any_shape() {
    let (err, at) = worst_absolute(&GAMMA_CDF, |&(a, x, want)| {
        (
            special::regularized_lower_gamma(a, x),
            want,
            format!("P(a={a}, x={x})"),
        )
    });
    assert!(err < 1e-9, "worst absolute error {err:e}: {at}");
}

/// `I_x(a, b)` at shapes from 1e4 to 1e12. Below 1e7 the continued fraction is
/// right to 1e-9; from 1e7 the normal limit with its first Edgeworth term has an
/// error of order `1/(a+b)`, 7e-9 where it starts (`I_x(1e7, 1e7)`, measured)
/// and falling with the shape -- "about 1e-9" in the 0.16.1 notes was 7e-9 at
/// its worst, so the bound here is 1e-8.
#[test]
fn the_regularized_incomplete_beta_is_right_to_1e_8_at_any_shape() {
    let (err, at) = worst_absolute(&BETA_CDF, |&(a, b, x, want)| {
        (
            special::regularized_incomplete_beta(x, a, b),
            want,
            format!("I_{x}({a}, {b})"),
        )
    });
    assert!(err < 1e-8, "worst absolute error {err:e}: {at}");
}
