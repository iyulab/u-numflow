/// Relative to the smaller tail, which is what a quantile built on the CDF resolves.
fn err(got: f64, want: f64) -> f64 {
    (got - want).abs() / want.min(1.0 - want).max(1e-300)
}

/// The large-`a` expansion (`a >= 15`, `b <= 30`, `a >= 8 b`, `x` past the middle)
/// and the continued fraction on both sides of its boundary: pairs such as
/// (40, 5.0) / (40, 5.1) and (20, 2.4) / (20, 2.6) sit either side of `a >= 8 b`, so a
/// jump between the two methods shows as a row off the line.
#[test]
fn the_grid_holds_one_line_across_the_expansion_boundary() {
    for &(x, a, b, want) in &GRID {
        let got = regularized_incomplete_beta(x, a, b);
        // Measured worst: 3.5e-14 for a small `b`, 1.1e-13 for shapes to 3e5, and
        // 1.1e-12 at 3e6 (the prefix and the continued fraction each carry
        // `~1e-19 * shape` of rounding there).
        let bound = if a.min(b) <= 3.0 {
            6e-14
        } else if a.max(b) <= 1e5 {
            2e-13
        } else {
            2e-12
        };
        assert!(
            err(got, want) <= bound,
            "I_{x:e}({a:e}, {b:e}) = {got:e}, want {want:e}: {:.2e} > {bound:.2e}",
            err(got, want)
        );
    }
}
