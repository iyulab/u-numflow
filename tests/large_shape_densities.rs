fn worst_relative<T>(rows: &[T], eval: impl Fn(&T) -> (f64, f64, String)) -> (f64, String) {
    let mut worst = (0.0_f64, String::new());
    for row in rows {
        let (got, want, label) = eval(row);
        let rel = (got - want).abs() / want.abs();
        if rel > worst.0 {
            worst = (rel, format!("{label}: {got:e} vs {want:e}"));
        }
    }
    worst
}

/// The density of Student's t at large degrees of freedom took
/// `ln Γ((ν+1)/2) − ln Γ(ν/2)` as the difference of two numbers of order
/// `ν ln ν` (a `ν` of 1e10 has a `ln Γ` whose last digit is 3e-5), and
/// `(ν+1)/2 · ln(1 + t²/ν)` with the 1 added first.
#[test]
fn the_t_density_keeps_its_digits_at_large_degrees_of_freedom() {
    let (rel, at) = worst_relative(&T_PDF, |&(nu, t, want)| {
        (
            special::t_distribution_pdf(t, nu),
            want,
            format!("t pdf(t={t}, df={nu})"),
        )
    });
    assert!(rel < 1e-12, "worst relative error {rel:e}: {at}");
}

/// The gamma and chi-squared densities subtract `ln Γ(a)` from `a ln(βx) − βx`,
/// three numbers of order `a ln a` that cancel to the order of `ln a`.
#[test]
fn the_gamma_and_chi_squared_densities_keep_their_digits_at_large_shapes() {
    let (rel, at) = worst_relative(&GAMMA_PDF, |&(a, rate, x, want)| {
        let g = distributions::GammaDistribution::new(a, rate).expect("valid");
        (
            g.pdf(x),
            want,
            format!("gamma pdf(x={x}; shape={a}, rate={rate})"),
        )
    });
    assert!(rel < 1e-12, "gamma: worst relative error {rel:e}: {at}");
    let (rel, at) = worst_relative(&CHI2_PDF, |&(k, x, want)| {
        let c = distributions::ChiSquared::new(k).expect("valid");
        (c.pdf(x), want, format!("chi2 pdf(x={x}; k={k})"))
    });
    assert!(
        rel < 1e-12,
        "chi-squared: worst relative error {rel:e}: {at}"
    );
}

/// `ln B(a, b)` against `ln Γ(a) + ln Γ(b) − ln Γ(a+b)` at 80 digits.
#[test]
fn ln_beta_matches_the_definition_at_80_digits() {
    let (rel, at) = worst_relative(&LN_BETA, |&(a, b, want)| {
        (special::ln_beta(a, b), want, format!("ln B({a}, {b})"))
    });
    assert!(rel < 1e-13, "worst relative error {rel:e}: {at}");
}
